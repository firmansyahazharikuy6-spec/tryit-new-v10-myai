export interface WordSectionSpec {
  heading: string;
  level?: 1 | 2 | 3;
  paragraphs?: string[];
  bullets?: string[];
  callout?: string;
  table?: {
    headers: string[];
    rows: Array<Array<string | number>>;
  };
}

export interface WordDocumentSpec {
  kind: 'word';
  title: string;
  subtitle?: string;
  author?: string;
  date?: string;
  sections: WordSectionSpec[];
}

export interface PptMetricSpec {
  label: string;
  value: string;
  delta?: string;
}

export interface PptSlideSpec {
  layout?: 'title' | 'bullets' | 'two-column' | 'metrics' | 'closing';
  title: string;
  subtitle?: string;
  bullets?: string[];
  metrics?: PptMetricSpec[];
  notes?: string;
}

export interface PptDeckSpec {
  kind: 'ppt';
  title: string;
  subtitle?: string;
  theme?: 'dark' | 'indigo' | 'emerald' | 'slate';
  slides: PptSlideSpec[];
}

export type ExcelCellInput = string | number | boolean | null | undefined;

export interface ExcelSheetSpec {
  name: string;
  columns: string[];
  rows: ExcelCellInput[][];
  summaryRow?: ExcelCellInput[];
  notes?: string;
}

export interface ExcelWorkbookSpec {
  kind: 'excel';
  title: string;
  sheets: ExcelSheetSpec[];
}

export type OfficeArtifactSpec =
  | WordDocumentSpec
  | PptDeckSpec
  | ExcelWorkbookSpec;

export function detectOfficeKindFromPath(
  filePath: string,
): 'word' | 'ppt' | 'excel' | null {
  const lower = filePath.toLowerCase();
  if (lower.endsWith('.docx.json') || lower.endsWith('.word.json')) return 'word';
  if (lower.endsWith('.pptx.json') || lower.endsWith('.ppt.json')) return 'ppt';
  if (lower.endsWith('.xlsx.json') || lower.endsWith('.excel.json')) return 'excel';
  return null;
}

function tryParseJsonRelaxed(raw: string): unknown | null {
  const trimmed = raw
    .trim()
    .replace(/^```[a-zA-Z0-9_.:-]*\n?/, '')
    .replace(/\n?```$/, '')
    .trim();
  if (!trimmed) return null;
  try {
    return JSON.parse(trimmed);
  } catch {
    // Strip trailing commas before ] or }
    const cleaned = trimmed.replace(/,\s*([}\]])/g, '$1');
    try {
      return JSON.parse(cleaned);
    } catch {
      return null;
    }
  }
}

function normalizeWordSpec(
  raw: Record<string, unknown>,
  fallbackTitle: string,
): WordDocumentSpec {
  const rawSections = Array.isArray(raw.sections) ? raw.sections : [];
  const sections: WordSectionSpec[] = rawSections.map((sec, idx) => {
    const s = (sec && typeof sec === 'object' ? sec : {}) as Record<
      string,
      unknown
    >;
    const rawTable =
      s.table && typeof s.table === 'object'
        ? (s.table as Record<string, unknown>)
        : null;
    return {
      heading: String(s.heading || `Section ${idx + 1}`),
      level: s.level === 2 || s.level === 3 ? s.level : 1,
      paragraphs: Array.isArray(s.paragraphs)
        ? s.paragraphs.map((p) => String(p))
        : undefined,
      bullets: Array.isArray(s.bullets)
        ? s.bullets.map((b) => String(b))
        : undefined,
      callout: typeof s.callout === 'string' ? s.callout : undefined,
      table: rawTable
        ? {
            headers: Array.isArray(rawTable.headers)
              ? rawTable.headers.map((h) => String(h))
              : [],
            rows: Array.isArray(rawTable.rows)
              ? rawTable.rows.map((r) =>
                  Array.isArray(r) ? r.map((c) => String(c ?? '')) : [],
                )
              : [],
          }
        : undefined,
    };
  });

  return {
    kind: 'word',
    title: String(raw.title || fallbackTitle || 'Project Document'),
    subtitle: typeof raw.subtitle === 'string' ? raw.subtitle : undefined,
    author: typeof raw.author === 'string' ? raw.author : 'MyAI Studio × MYRA',
    date:
      typeof raw.date === 'string'
        ? raw.date
        : new Date().toISOString().slice(0, 10),
    sections:
      sections.length > 0
        ? sections
        : [
            {
              heading: 'Overview',
              level: 1,
              paragraphs: ['Document content generated by MyAI Studio.'],
            },
          ],
  };
}

function normalizePptSpec(
  raw: Record<string, unknown>,
  fallbackTitle: string,
): PptDeckSpec {
  const rawSlides = Array.isArray(raw.slides) ? raw.slides : [];
  const slides: PptSlideSpec[] = rawSlides.map((slide, idx) => {
    const s = (slide && typeof slide === 'object' ? slide : {}) as Record<
      string,
      unknown
    >;
    const layout =
      s.layout === 'title' ||
      s.layout === 'bullets' ||
      s.layout === 'two-column' ||
      s.layout === 'metrics' ||
      s.layout === 'closing'
        ? s.layout
        : idx === 0
          ? 'title'
          : 'bullets';
    return {
      layout,
      title: String(s.title || `Slide ${idx + 1}`),
      subtitle: typeof s.subtitle === 'string' ? s.subtitle : undefined,
      bullets: Array.isArray(s.bullets)
        ? s.bullets.map((b) => String(b))
        : undefined,
      metrics: Array.isArray(s.metrics)
        ? s.metrics.map((m) => {
            const item = (m && typeof m === 'object' ? m : {}) as Record<
              string,
              unknown
            >;
            return {
              label: String(item.label || 'Metric'),
              value: String(item.value || '—'),
              delta: typeof item.delta === 'string' ? item.delta : undefined,
            };
          })
        : undefined,
      notes: typeof s.notes === 'string' ? s.notes : undefined,
    };
  });

  const theme =
    raw.theme === 'dark' ||
    raw.theme === 'emerald' ||
    raw.theme === 'slate' ||
    raw.theme === 'indigo'
      ? raw.theme
      : 'indigo';

  return {
    kind: 'ppt',
    title: String(raw.title || fallbackTitle || 'Presentation Deck'),
    subtitle: typeof raw.subtitle === 'string' ? raw.subtitle : undefined,
    theme,
    slides:
      slides.length > 0
        ? slides
        : [
            {
              layout: 'title',
              title: String(raw.title || fallbackTitle || 'Presentation Deck'),
              subtitle: 'Generated by MyAI Studio × MYRA',
            },
          ],
  };
}

function normalizeExcelSpec(
  raw: Record<string, unknown>,
  fallbackTitle: string,
): ExcelWorkbookSpec {
  const rawSheets = Array.isArray(raw.sheets) ? raw.sheets : [];
  const sheets: ExcelSheetSpec[] = rawSheets.map((sheet, idx) => {
    const s = (sheet && typeof sheet === 'object' ? sheet : {}) as Record<
      string,
      unknown
    >;
    const safeName =
      String(s.name || `Sheet${idx + 1}`)
        .replace(/[\\/*?:[\]]/g, '')
        .slice(0, 31) || `Sheet${idx + 1}`;
    const columns = Array.isArray(s.columns)
      ? s.columns.map((c) => String(c))
      : [];
    const rows = Array.isArray(s.rows)
      ? s.rows.map((r) =>
          Array.isArray(r)
            ? r.map((cell) =>
                typeof cell === 'number' ||
                typeof cell === 'boolean' ||
                typeof cell === 'string'
                  ? cell
                  : cell == null
                    ? ''
                    : String(cell),
              )
            : [],
        )
      : [];
    const summaryRow = Array.isArray(s.summaryRow)
      ? s.summaryRow.map((cell) =>
          typeof cell === 'number' ||
          typeof cell === 'boolean' ||
          typeof cell === 'string'
            ? cell
            : cell == null
              ? ''
              : String(cell),
        )
      : undefined;

    return {
      name: safeName,
      columns,
      rows,
      summaryRow,
      notes: typeof s.notes === 'string' ? s.notes : undefined,
    };
  });

  return {
    kind: 'excel',
    title: String(raw.title || fallbackTitle || 'Workbook'),
    sheets:
      sheets.length > 0
        ? sheets
        : [
            {
              name: 'Sheet1',
              columns: ['Item', 'Value'],
              rows: [['Sample', 0]],
            },
          ],
  };
}

export function parseOfficeSpecFromFile(
  file: WorkspaceFile,
): OfficeArtifactSpec | null {
  const pathKind = detectOfficeKindFromPath(file.path);
  const parsed = tryParseJsonRelaxed(file.content);
  const baseName =
    file.path
      .split('/')
      .pop()
      ?.replace(/\.(docx|pptx|xlsx|word|ppt|excel)\.json$/i, '') || 'Project';

  if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
    const obj = parsed as Record<string, unknown>;
    const kind =
      obj.kind === 'word' || obj.kind === 'ppt' || obj.kind === 'excel'
        ? obj.kind
        : pathKind;
    if (kind === 'word') return normalizeWordSpec(obj, baseName);
    if (kind === 'ppt') return normalizePptSpec(obj, baseName);
    if (kind === 'excel') return normalizeExcelSpec(obj, baseName);
  }

  // Fallback for CSV files so users can preview & download as .xlsx
  if (file.path.toLowerCase().endsWith('.csv') || file.language === 'csv') {
    const lines = file.content
      .split(/\r?\n/)
      .map((l) => l.trim())
      .filter(Boolean);
    if (lines.length > 0) {
      const splitLine = (line: string) =>
        line.split(',').map((cell) => {
          const clean = cell.trim().replace(/^"|"$/g, '');
          const num = Number(clean);
          return clean !== '' && !Number.isNaN(num) ? num : clean;
        });
      const columns = splitLine(lines[0]).map(String);
      const rows = lines.slice(1).map(splitLine);
      return {
        kind: 'excel',
        title: baseName,
        sheets: [{ name: 'Data', columns, rows }],
      };
    }
  }

  return null;
}

function colLettersToIndex(letters: string): number {
  let idx = 0;
  for (let i = 0; i < letters.length; i++) {
    idx = idx * 26 + (letters.charCodeAt(i) - 64);
  }
  return idx - 1;
}

/**
 * Evaluates common spreadsheet formulas (=SUM(B2:E2), =AVERAGE(B2:B5), =B2+C2, =B2-C2, =B2*C2)
 * for instant interactive preview in the Workbench before exporting to .xlsx.
 */
export function evaluateSheetCellDisplay(
  sheet: ExcelSheetSpec,
  rowIdx: number, // 0-based index into allDataRows (rows + optional summaryRow)
  colIdx: number,
  visited = new Set<string>(),
): string {
  const allRows = sheet.summaryRow
    ? [...sheet.rows, sheet.summaryRow]
    : sheet.rows;
  const rawVal = allRows[rowIdx]?.[colIdx];
  if (rawVal === null || rawVal === undefined) return '';
  if (typeof rawVal === 'number') {
    return Number.isInteger(rawVal)
      ? rawVal.toLocaleString('en-US')
      : rawVal.toLocaleString('en-US', { maximumFractionDigits: 2 });
  }
  if (typeof rawVal === 'boolean') return rawVal ? 'TRUE' : 'FALSE';
  const str = String(rawVal).trim();
  if (!str.startsWith('=')) return str;

  const cellKey = `${rowIdx}:${colIdx}`;
  if (visited.has(cellKey)) return str;
  visited.add(cellKey);

  const expr = str.slice(1).trim().toUpperCase();

  const resolveNumericCell = (ref: string): number => {
    const m = /^([A-Z]+)(\d+)$/.exec(ref.trim());
    if (!m) return 0;
    const c = colLettersToIndex(m[1]);
    const r = Number(m[2]) - 2; // Row 1 is column headers; Row 2 is rows[0]
    if (r < 0 || r >= allRows.length || c < 0) return 0;
    const rawTarget = allRows[r]?.[c];
    if (typeof rawTarget === 'number') return rawTarget;
    if (typeof rawTarget === 'string' && rawTarget.trim().startsWith('=')) {
      const evaluated = Number(
        evaluateSheetCellDisplay(sheet, r, c, new Set(visited)).replace(/,/g, ''),
      );
      return Number.isFinite(evaluated) ? evaluated : 0;
    }
    const n = Number(String(rawTarget ?? '').replace(/,/g, ''));
    return Number.isFinite(n) ? n : 0;
  };

  const rangeMatch = /^(SUM|AVERAGE|AVG|MIN|MAX|COUNT)\(([A-Z]+\d+):([A-Z]+\d+)\)$/.exec(
    expr,
  );
  if (rangeMatch) {
    const fn = rangeMatch[1];
    const startMatch = /^([A-Z]+)(\d+)$/.exec(rangeMatch[2]);
    const endMatch = /^([A-Z]+)(\d+)$/.exec(rangeMatch[3]);
    if (startMatch && endMatch) {
      const c1 = colLettersToIndex(startMatch[1]);
      const r1 = Number(startMatch[2]) - 2;
      const c2 = colLettersToIndex(endMatch[1]);
      const r2 = Number(endMatch[2]) - 2;
      const vals: number[] = [];
      for (let r = Math.min(r1, r2); r <= Math.max(r1, r2); r++) {
        for (let c = Math.min(c1, c2); c <= Math.max(c1, c2); c++) {
          if (r >= 0 && r < allRows.length && c >= 0) {
            const cellLetter = String.fromCharCode(65 + c);
            vals.push(resolveNumericCell(`${cellLetter}${r + 2}`));
          }
        }
      }
      if (vals.length === 0) return '0';
      let result = 0;
      if (fn === 'SUM') result = vals.reduce((a, b) => a + b, 0);
      else if (fn === 'AVERAGE' || fn === 'AVG')
        result = vals.reduce((a, b) => a + b, 0) / vals.length;
      else if (fn === 'MIN') result = Math.min(...vals);
      else if (fn === 'MAX') result = Math.max(...vals);
      else if (fn === 'COUNT') result = vals.length;
      return Number.isInteger(result)
        ? result.toLocaleString('en-US')
        : result.toLocaleString('en-US', { maximumFractionDigits: 2 });
    }
  }

  const binMatch = /^([A-Z]+\d+)\s*([+\-*/])\s*([A-Z]+\d+|\d+(?:\.\d+)?)$/.exec(
    expr,
  );
  if (binMatch) {
    const left = resolveNumericCell(binMatch[1]);
    const op = binMatch[2];
    const right = /^[A-Z]+\d+$/.test(binMatch[3])
      ? resolveNumericCell(binMatch[3])
      : Number(binMatch[3]);
    let res = 0;
    if (op === '+') res = left + right;
    else if (op === '-') res = left - right;
    else if (op === '*') res = left * right;
    else if (op === '/') res = right !== 0 ? left / right : 0;
    return Number.isInteger(res)
      ? res.toLocaleString('en-US')
      : res.toLocaleString('en-US', { maximumFractionDigits: 2 });
  }

  return str;
}

export async function generateDocxUint8Array(
  spec: WordDocumentSpec,
): Promise<Uint8Array> {
  const children: Array<Paragraph | Table> = [
    new Paragraph({
      text: spec.title,
      heading: HeadingLevel.TITLE,
      spacing: { after: 120 },
    }),
  ];

  if (spec.subtitle) {
    children.push(
      new Paragraph({
        children: [
          new TextRun({
            text: spec.subtitle,
            color: '4F46E5',
            size: 24,
            italics: true,
          }),
        ],
        spacing: { after: 120 },
      }),
    );
  }

  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: `${spec.author || 'MyAI Studio × MYRA'}  |  ${spec.date || new Date().toISOString().slice(0, 10)}`,
          size: 18,
          color: '71717A',
        }),
      ],
      spacing: { after: 280 },
      border: {
        bottom: { style: BorderStyle.SINGLE, size: 6, color: 'E4E4E7' },
      },
    }),
  );

  for (const sec of spec.sections) {
    const headingLvl =
      sec.level === 2
        ? HeadingLevel.HEADING_2
        : sec.level === 3
          ? HeadingLevel.HEADING_3
          : HeadingLevel.HEADING_1;

    children.push(
      new Paragraph({
        text: sec.heading,
        heading: headingLvl,
        spacing: { before: 240, after: 100 },
      }),
    );

    if (sec.callout) {
      children.push(
        new Paragraph({
          children: [
            new TextRun({
              text: sec.callout,
              bold: true,
              color: '312E81',
              size: 21,
            }),
          ],
          shading: { type: ShadingType.CLEAR, fill: 'EEF2FF' },
          spacing: { before: 80, after: 140 },
          indent: { left: 180, right: 180 },
        }),
      );
    }

    for (const para of sec.paragraphs ?? []) {
      children.push(
        new Paragraph({
          text: para,
          spacing: { after: 120 },
          alignment: AlignmentType.LEFT,
        }),
      );
    }

    for (const bullet of sec.bullets ?? []) {
      children.push(
        new Paragraph({
          text: bullet,
          bullet: { level: 0 },
          spacing: { after: 60 },
        }),
      );
    }

    if (sec.table && sec.table.headers.length > 0) {
      const headerRow = new TableRow({
        tableHeader: true,
        children: sec.table.headers.map(
          (h) =>
            new TableCell({
              shading: { type: ShadingType.CLEAR, fill: '4F46E5' },
              children: [
                new Paragraph({
                  children: [
                    new TextRun({ text: h, bold: true, color: 'FFFFFF', size: 20 }),
                  ],
                }),
              ],
            }),
        ),
      });

      const bodyRows = sec.table.rows.map(
        (row) =>
          new TableRow({
            children: sec.table!.headers.map(
              (_h, idx) =>
                new TableCell({
                  children: [
                    new Paragraph({
                      children: [
                        new TextRun({ text: String(row[idx] ?? ''), size: 20 }),
                      ],
                    }),
                  ],
                }),
            ),
          }),
      );

      children.push(
        new Table({
          width: { size: 100, type: WidthType.PERCENTAGE },
          rows: [headerRow, ...bodyRows],
        }),
      );
    }
  }

  const doc = new Document({
    creator: spec.author || 'MyAI Studio',
    title: spec.title,
    sections: [{ children }],
  });

  const arrayBuf = await Packer.toArrayBuffer(doc);
  return new Uint8Array(arrayBuf);
}

export async function generatePptxUint8Array(
  spec: PptDeckSpec,
): Promise<Uint8Array> {
  const pptx = new PptxGenJS();
  pptx.layout = 'LAYOUT_WIDE';
  pptx.title = spec.title;
  pptx.author = 'MyAI Studio × MYRA';

  const paletteMap = {
    indigo: { bg: '0F1020', card: '1B1D36', accent: '6366F1', text: 'F4F4F5', muted: 'A1A1AA' },
    dark: { bg: '09090B', card: '18181B', accent: '818CF8', text: 'FAFAFA', muted: 'A1A1AA' },
    emerald: { bg: '061812', card: '0E2920', accent: '10B981', text: 'ECFDF5', muted: 'A7F3D0' },
    slate: { bg: 'F8FAFC', card: 'FFFFFF', accent: '4F46E5', text: '0F172A', muted: '475569' },
  } as const;
  const pal = paletteMap[spec.theme || 'indigo'];

  for (const s of spec.slides) {
    const slide = pptx.addSlide();
    slide.background = { color: pal.bg };

    if (s.notes) {
      slide.addNotes(s.notes);
    }

    if (s.layout === 'title') {
      slide.addShape(pptx.ShapeType.rect, {
        x: 0.7,
        y: 1.5,
        w: 1.4,
        h: 0.08,
        fill: { color: pal.accent },
      });
      slide.addText(s.title, {
        x: 0.7,
        y: 1.85,
        w: 11.8,
        h: 1.5,
        fontSize: 36,
        bold: true,
        color: pal.text,
      });
      if (s.subtitle || spec.subtitle) {
        slide.addText(s.subtitle || spec.subtitle || '', {
          x: 0.7,
          y: 3.45,
          w: 11.5,
          h: 1.0,
          fontSize: 18,
          color: pal.muted,
        });
      }
      slide.addText('MyAI Studio × MYRA Deck', {
        x: 0.7,
        y: 6.5,
        w: 6.0,
        h: 0.4,
        fontSize: 11,
        color: pal.accent,
      });
      continue;
    }

    slide.addText(s.title, {
      x: 0.7,
      y: 0.45,
      w: 11.8,
      h: 0.7,
      fontSize: 24,
      bold: true,
      color: pal.text,
    });

    if (s.subtitle) {
      slide.addText(s.subtitle, {
        x: 0.7,
        y: 1.15,
        w: 11.8,
        h: 0.45,
        fontSize: 14,
        color: pal.muted,
      });
    }

    let yCursor = s.subtitle ? 1.8 : 1.35;

    if (s.metrics && s.metrics.length > 0) {
      const count = Math.min(s.metrics.length, 4);
      const cardW = (11.8 - (count - 1) * 0.3) / count;
      s.metrics.slice(0, 4).forEach((m, i) => {
        const x = 0.7 + i * (cardW + 0.3);
        slide.addShape(pptx.ShapeType.roundRect, {
          x,
          y: yCursor,
          w: cardW,
          h: 1.55,
          fill: { color: pal.card },
          line: { color: pal.accent, width: 1 },
        });
        slide.addText(m.label, {
          x: x + 0.2,
          y: yCursor + 0.18,
          w: cardW - 0.4,
          h: 0.35,
          fontSize: 11,
          color: pal.muted,
        });
        slide.addText(m.value, {
          x: x + 0.2,
          y: yCursor + 0.55,
          w: cardW - 0.4,
          h: 0.55,
          fontSize: 24,
          bold: true,
          color: pal.text,
        });
        if (m.delta) {
          slide.addText(m.delta, {
            x: x + 0.2,
            y: yCursor + 1.1,
            w: cardW - 0.4,
            h: 0.3,
            fontSize: 11,
            color: pal.accent,
          });
        }
      });
      yCursor += 1.85;
    }

    if (s.bullets && s.bullets.length > 0) {
      slide.addText(
        s.bullets.map((b) => ({
          text: b,
          options: { bullet: true, breakLine: true },
        })),
        {
          x: 0.75,
          y: yCursor,
          w: 11.7,
          h: 6.7 - yCursor,
          fontSize: 15,
          color: pal.text,
          paraSpaceAfter: 10,
          valign: 'top',
        },
      );
    }
  }

  const out = (await pptx.write({ outputType: 'uint8array' })) as Uint8Array;
  return out;
}

export function generateXlsxUint8Array(spec: ExcelWorkbookSpec): Uint8Array {
  const wb = XLSX.utils.book_new();

  for (const sheet of spec.sheets) {
    const aoa: Array<Array<string | number | boolean | null>> = [];
    if (sheet.columns.length > 0) {
      aoa.push(sheet.columns);
    }
    for (const row of sheet.rows) {
      aoa.push(row.map((c) => (c === undefined ? null : c)));
    }
    if (sheet.summaryRow && sheet.summaryRow.length > 0) {
      aoa.push(sheet.summaryRow.map((c) => (c === undefined ? null : c)));
    }

    const ws = XLSX.utils.aoa_to_sheet(aoa);

    // Convert cells beginning with '=' into native Excel formula cells
    for (let r = 0; r < aoa.length; r++) {
      for (let c = 0; c < aoa[r].length; c++) {
        const val = aoa[r][c];
        if (typeof val === 'string' && val.trim().startsWith('=')) {
          const addr = XLSX.utils.encode_cell({ r, c });
          ws[addr] = { t: 'n', f: val.trim().slice(1) };
        }
      }
    }

    // Set comfortable column widths
    const colCount = Math.max(
      sheet.columns.length,
      ...sheet.rows.map((r) => r.length),
      1,
    );
    ws['!cols'] = Array.from({ length: colCount }, (_, colIdx) => {
      const maxLen = Math.max(
        10,
        ...aoa.map((r) => String(r[colIdx] ?? '').length),
      );
      return { wch: Math.min(38, maxLen + 4) };
    });

    const safeSheetName =
      sheet.name.replace(/[\\/*?:[\]]/g, '').slice(0, 31) || 'Sheet1';
    XLSX.utils.book_append_sheet(wb, ws, safeSheetName);
  }

  const rawArray = XLSX.write(wb, { type: 'array', bookType: 'xlsx' }) as
    | ArrayBuffer
    | Uint8Array;
  return rawArray instanceof Uint8Array ? rawArray : new Uint8Array(rawArray);
}

export async function exportOfficeFileDownload(
  spec: OfficeArtifactSpec,
  suggestedBaseName: string,
): Promise<void> {
  const cleanName =
    suggestedBaseName
      .replace(/\.(docx|pptx|xlsx|word|ppt|excel)\.json$/i, '')
      .replace(/\.(docx|pptx|xlsx|csv|md)$/i, '')
      .trim() || 'myai-artifact';

  let bytes: Uint8Array;
  let ext: 'docx' | 'pptx' | 'xlsx';
  let mime: string;

  if (spec.kind === 'word') {
    bytes = await generateDocxUint8Array(spec);
    ext = 'docx';
    mime =
      'application/vnd.openxmlformats-officedocument.wordprocessingml.document';
  } else if (spec.kind === 'ppt') {
    bytes = await generatePptxUint8Array(spec);
    ext = 'pptx';
    mime =
      'application/vnd.openxmlformats-officedocument.presentationml.presentation';
  } else {
    bytes = generateXlsxUint8Array(spec);
    ext = 'xlsx';
    mime =
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';
  }

  const copy = new Uint8Array(bytes.byteLength);
  copy.set(bytes);
  const blob = new Blob([copy.buffer], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${cleanName}.${ext}`;
  a.click();
  URL.revokeObjectURL(url);
}
